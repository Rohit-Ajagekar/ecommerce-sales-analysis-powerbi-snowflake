-- Retail Analytics Dashboard | Business analysis queries (Snowflake SQL)
-- Run after selecting the database/schema containing the project tables.
-- Example: USE DATABASE <YOUR_DATABASE>; USE SCHEMA <YOUR_SCHEMA>;
-- Assumes SALES_TRANSACTIONS is the anomaly/working dataset and
-- SALES_TRANSACTIONS_CLEAN is the clean baseline dataset.

-- 1. Executive KPIs: revenue, units, receipts, customers, and gross profit.
-- Gross profit uses quantity * SKU cost price as the estimated cost of goods sold.
SELECT
    SUM(s.TOTAL_VALUE) AS TOTAL_REVENUE,
    SUM(s.QUANTITY) AS TOTAL_UNITS,
    COUNT(DISTINCT s.RECEIPT_ID) AS TOTAL_TRANSACTIONS,
    COUNT(DISTINCT s.CUSTOMER_ID) AS TOTAL_CUSTOMERS,
    SUM(s.TOTAL_VALUE) - SUM(s.QUANTITY * sk.COST_PRICE) AS GROSS_PROFIT,
    DIV0(
        SUM(s.TOTAL_VALUE) - SUM(s.QUANTITY * sk.COST_PRICE),
        SUM(s.TOTAL_VALUE)
    ) AS GROSS_MARGIN_RATE
FROM SALES_TRANSACTIONS s
LEFT JOIN SKU_MASTER sk ON s.SKU_ID = sk.SKU_ID;

-- 2. Monthly sales trend
SELECT
    DATE_TRUNC('MONTH', TRANSACTION_DATE) AS SALES_MONTH,
    SUM(TOTAL_VALUE) AS TOTAL_REVENUE,
    SUM(QUANTITY) AS TOTAL_UNITS,
    COUNT(DISTINCT RECEIPT_ID) AS TOTAL_TRANSACTIONS
FROM SALES_TRANSACTIONS
GROUP BY DATE_TRUNC('MONTH', TRANSACTION_DATE)
ORDER BY SALES_MONTH;

-- 3. Revenue and gross profit by city
SELECT
    st.CITY,
    SUM(s.TOTAL_VALUE) AS TOTAL_REVENUE,
    SUM(s.TOTAL_VALUE) - SUM(s.QUANTITY * sk.COST_PRICE) AS GROSS_PROFIT,
    DIV0(
        SUM(s.TOTAL_VALUE) - SUM(s.QUANTITY * sk.COST_PRICE),
        SUM(s.TOTAL_VALUE)
    ) AS GROSS_MARGIN_RATE
FROM SALES_TRANSACTIONS s
JOIN STORE_MASTER st ON s.STORE_ID = st.STORE_ID
JOIN SKU_MASTER sk ON s.SKU_ID = sk.SKU_ID
GROUP BY st.CITY
ORDER BY TOTAL_REVENUE DESC;

-- 4. Top 5 stores by revenue
SELECT
    st.STORE_ID,
    st.STORE_NAME,
    st.CITY,
    SUM(s.TOTAL_VALUE) AS TOTAL_REVENUE,
    RANK() OVER (ORDER BY SUM(s.TOTAL_VALUE) DESC) AS REVENUE_RANK
FROM SALES_TRANSACTIONS s
JOIN STORE_MASTER st ON s.STORE_ID = st.STORE_ID
GROUP BY st.STORE_ID, st.STORE_NAME, st.CITY
QUALIFY REVENUE_RANK <= 5
ORDER BY REVENUE_RANK;

-- 5. Category performance
SELECT
    sk.CATEGORY,
    SUM(s.TOTAL_VALUE) AS TOTAL_REVENUE,
    SUM(s.QUANTITY) AS TOTAL_UNITS,
    SUM(s.TOTAL_VALUE) - SUM(s.QUANTITY * sk.COST_PRICE) AS GROSS_PROFIT,
    DIV0(
        SUM(s.TOTAL_VALUE) - SUM(s.QUANTITY * sk.COST_PRICE),
        SUM(s.TOTAL_VALUE)
    ) AS GROSS_MARGIN_RATE
FROM SALES_TRANSACTIONS s
JOIN SKU_MASTER sk ON s.SKU_ID = sk.SKU_ID
GROUP BY sk.CATEGORY
ORDER BY TOTAL_REVENUE DESC;

-- 6. Promotion performance. Rows without a valid PROMO_ID are treated as non-promotional.
SELECT
    COALESCE(p.PROMO_TYPE, 'Unknown / Unmatched Promotion') AS PROMO_TYPE,
    COUNT(DISTINCT s.RECEIPT_ID) AS TRANSACTIONS,
    SUM(s.TOTAL_VALUE) AS TOTAL_REVENUE,
    SUM(s.QUANTITY) AS TOTAL_UNITS
FROM SALES_TRANSACTIONS s
LEFT JOIN PROMOTIONS p
    ON s.PROMO_ID = p.PROMO_ID
   AND s.PROMO_ID IS NOT NULL
   AND TRIM(s.PROMO_ID) <> ''
   AND UPPER(TRIM(s.PROMO_ID)) <> 'NULL'
GROUP BY COALESCE(p.PROMO_TYPE, 'Unknown / Unmatched Promotion')
ORDER BY TOTAL_REVENUE DESC;

-- 7. Revenue by customer loyalty segment and preferred channel
SELECT
    c.LOYALTY_SEGMENT,
    c.PREFERRED_CHANNEL,
    SUM(s.TOTAL_VALUE) AS TOTAL_REVENUE,
    COUNT(DISTINCT s.CUSTOMER_ID) AS CUSTOMERS,
    COUNT(DISTINCT s.RECEIPT_ID) AS TRANSACTIONS
FROM SALES_TRANSACTIONS s
LEFT JOIN CUSTOMER_MASTER c ON s.CUSTOMER_ID = c.CUST_ID
GROUP BY c.LOYALTY_SEGMENT, c.PREFERRED_CHANNEL
ORDER BY TOTAL_REVENUE DESC;

-- 8. Current inventory status by store and SKU.
-- Status thresholds are project rules, not universal retail definitions.
SELECT
    i.STORE_ID,
    st.STORE_NAME,
    i.SKU_ID,
    sk.SKU_NAME,
    i.STOCK_ON_HAND,
    i.SAFETY_STOCK,
    i.REORDER_POINT,
    CASE
        WHEN i.STOCK_ON_HAND = 0 THEN 'Out of Stock'
        WHEN i.STOCK_ON_HAND < i.SAFETY_STOCK THEN 'Low Stock'
        WHEN i.STOCK_ON_HAND < i.REORDER_POINT THEN 'Reorder Required'
        ELSE 'Healthy'
    END AS INVENTORY_STATUS,
    i.STOCK_ON_HAND * sk.COST_PRICE AS INVENTORY_VALUE
FROM INVENTORY_SNAPSHOT i
LEFT JOIN STORE_MASTER st ON i.STORE_ID = st.STORE_ID
LEFT JOIN SKU_MASTER sk ON i.SKU_ID = sk.SKU_ID
ORDER BY
    CASE
        WHEN i.STOCK_ON_HAND = 0 THEN 1
        WHEN i.STOCK_ON_HAND < i.SAFETY_STOCK THEN 2
        WHEN i.STOCK_ON_HAND < i.REORDER_POINT THEN 3
        ELSE 4
    END,
    i.STOCK_ON_HAND ASC;

-- 9. Inventory anomaly flags summary
SELECT
    UPPER(TRIM(FLAG)) AS FLAG_TYPE,
    COUNT(*) AS FLAG_RECORDS,
    COUNT(DISTINCT SKU_ID) AS DISTINCT_SKUS,
    SUM(AFFECTED_STORES) AS SUM_AFFECTED_STORES
FROM SKU_INVENTORY_FLAGS
GROUP BY UPPER(TRIM(FLAG))
ORDER BY FLAG_RECORDS DESC;

-- 10. Baseline vs anomaly dataset comparison by month.
-- Treat the difference as an observed dataset gap, NOT verified real-world lost sales.
WITH baseline AS (
    SELECT
        DATE_TRUNC('MONTH', TRANSACTION_DATE) AS SALES_MONTH,
        SUM(TOTAL_VALUE) AS BASELINE_REVENUE,
        SUM(QUANTITY) AS BASELINE_UNITS
    FROM SALES_TRANSACTIONS_CLEAN
    GROUP BY DATE_TRUNC('MONTH', TRANSACTION_DATE)
),
anomaly AS (
    SELECT
        DATE_TRUNC('MONTH', TRANSACTION_DATE) AS SALES_MONTH,
        SUM(TOTAL_VALUE) AS ANOMALY_REVENUE,
        SUM(QUANTITY) AS ANOMALY_UNITS
    FROM SALES_TRANSACTIONS
    GROUP BY DATE_TRUNC('MONTH', TRANSACTION_DATE)
)
SELECT
    COALESCE(b.SALES_MONTH, a.SALES_MONTH) AS SALES_MONTH,
    b.BASELINE_REVENUE,
    a.ANOMALY_REVENUE,
    b.BASELINE_REVENUE - a.ANOMALY_REVENUE AS ESTIMATED_REVENUE_GAP,
    b.BASELINE_UNITS,
    a.ANOMALY_UNITS,
    b.BASELINE_UNITS - a.ANOMALY_UNITS AS ESTIMATED_UNIT_GAP
FROM baseline b
FULL OUTER JOIN anomaly a ON b.SALES_MONTH = a.SALES_MONTH
ORDER BY SALES_MONTH;

-- 11. Estimated revenue gap by store.
-- This comparison is meaningful only if both fact tables are matched scenarios
-- with comparable periods and grain. It is not proof of causal lost sales.
WITH baseline AS (
    SELECT STORE_ID, SUM(TOTAL_VALUE) AS BASELINE_REVENUE
    FROM SALES_TRANSACTIONS_CLEAN
    GROUP BY STORE_ID
),
anomaly AS (
    SELECT STORE_ID, SUM(TOTAL_VALUE) AS ANOMALY_REVENUE
    FROM SALES_TRANSACTIONS
    GROUP BY STORE_ID
)
SELECT
    COALESCE(b.STORE_ID, a.STORE_ID) AS STORE_ID,
    st.STORE_NAME,
    b.BASELINE_REVENUE,
    a.ANOMALY_REVENUE,
    b.BASELINE_REVENUE - a.ANOMALY_REVENUE AS ESTIMATED_REVENUE_GAP
FROM baseline b
FULL OUTER JOIN anomaly a ON b.STORE_ID = a.STORE_ID
LEFT JOIN STORE_MASTER st ON st.STORE_ID = COALESCE(b.STORE_ID, a.STORE_ID)
ORDER BY ESTIMATED_REVENUE_GAP DESC;
