-- Retail Analytics Dashboard | Snowflake data validation
-- Run after selecting the database/schema containing the project tables.
-- Example: USE DATABASE <YOUR_DATABASE>; USE SCHEMA <YOUR_SCHEMA>;
-- These queries are read-only. They do not modify source data.

-- 1. Row counts for core tables
SELECT 'SALES_TRANSACTIONS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM SALES_TRANSACTIONS
UNION ALL
SELECT 'SALES_TRANSACTIONS_CLEAN', COUNT(*) FROM SALES_TRANSACTIONS_CLEAN
UNION ALL
SELECT 'STORE_MASTER', COUNT(*) FROM STORE_MASTER
UNION ALL
SELECT 'SKU_MASTER', COUNT(*) FROM SKU_MASTER
UNION ALL
SELECT 'CUSTOMER_MASTER', COUNT(*) FROM CUSTOMER_MASTER
UNION ALL
SELECT 'PROMOTIONS', COUNT(*) FROM PROMOTIONS
UNION ALL
SELECT 'INVENTORY_SNAPSHOT', COUNT(*) FROM INVENTORY_SNAPSHOT
UNION ALL
SELECT 'SKU_INVENTORY_FLAGS', COUNT(*) FROM SKU_INVENTORY_FLAGS;

-- 2. Sales coverage and basic metric checks
SELECT
    MIN(TRANSACTION_DATE) AS FIRST_TRANSACTION_DATE,
    MAX(TRANSACTION_DATE) AS LAST_TRANSACTION_DATE,
    COUNT(*) AS TRANSACTION_LINES,
    COUNT(DISTINCT RECEIPT_ID) AS DISTINCT_RECEIPTS,
    SUM(QUANTITY) AS TOTAL_UNITS,
    SUM(TOTAL_VALUE) AS TOTAL_REVENUE,
    SUM(IFF(TRANSACTION_DATE IS NULL, 1, 0)) AS NULL_TRANSACTION_DATES,
    SUM(IFF(STORE_ID IS NULL, 1, 0)) AS NULL_STORE_IDS,
    SUM(IFF(SKU_ID IS NULL, 1, 0)) AS NULL_SKU_IDS,
    SUM(IFF(QUANTITY IS NULL, 1, 0)) AS NULL_QUANTITIES,
    SUM(IFF(TOTAL_VALUE IS NULL, 1, 0)) AS NULL_TOTAL_VALUES
FROM SALES_TRANSACTIONS;

-- 3. Check for invalid quantities or negative transaction values.
-- Negative values may be valid returns/adjustments; review before excluding them.
SELECT
    COUNT_IF(QUANTITY IS NULL) AS NULL_QUANTITY_ROWS,
    COUNT_IF(QUANTITY <= 0) AS NONPOSITIVE_QUANTITY_ROWS,
    COUNT_IF(TOTAL_VALUE IS NULL) AS NULL_TOTAL_VALUE_ROWS,
    COUNT_IF(TOTAL_VALUE < 0) AS NEGATIVE_TOTAL_VALUE_ROWS,
    COUNT_IF(UNIT_PRICE < 0) AS NEGATIVE_UNIT_PRICE_ROWS
FROM SALES_TRANSACTIONS;

-- 4. Sales records with missing store, SKU, or customer dimension matches.
SELECT
    COUNT_IF(st.STORE_ID IS NULL) AS SALES_WITH_UNKNOWN_STORE,
    COUNT_IF(sk.SKU_ID IS NULL) AS SALES_WITH_UNKNOWN_SKU,
    COUNT_IF(c.CUST_ID IS NULL) AS SALES_WITH_UNKNOWN_CUSTOMER
FROM SALES_TRANSACTIONS s
LEFT JOIN STORE_MASTER st ON s.STORE_ID = st.STORE_ID
LEFT JOIN SKU_MASTER sk ON s.SKU_ID = sk.SKU_ID
LEFT JOIN CUSTOMER_MASTER c ON s.CUSTOMER_ID = c.CUST_ID;

-- 5. Check inventory rows that do not match the store or SKU dimensions.
SELECT
    COUNT(*) AS INVENTORY_ROWS,
    COUNT_IF(st.STORE_ID IS NULL) AS INVENTORY_WITH_UNKNOWN_STORE,
    COUNT_IF(sk.SKU_ID IS NULL) AS INVENTORY_WITH_UNKNOWN_SKU,
    COUNT_IF(i.STOCK_ON_HAND IS NULL) AS NULL_STOCK_ROWS,
    COUNT_IF(i.STOCK_ON_HAND < 0) AS NEGATIVE_STOCK_ROWS
FROM INVENTORY_SNAPSHOT i
LEFT JOIN STORE_MASTER st ON i.STORE_ID = st.STORE_ID
LEFT JOIN SKU_MASTER sk ON i.SKU_ID = sk.SKU_ID;

-- 6. Inventory flag distribution
SELECT
    UPPER(TRIM(FLAG)) AS FLAG_TYPE,
    COUNT(*) AS FLAG_ROWS,
    COUNT(DISTINCT SKU_ID) AS DISTINCT_SKUS
FROM SKU_INVENTORY_FLAGS
GROUP BY UPPER(TRIM(FLAG))
ORDER BY FLAG_ROWS DESC;

-- 7. Review missing or placeholder promotion IDs.
SELECT
    COUNT(*) AS TOTAL_SALES_ROWS,
    COUNT_IF(PROMO_ID IS NULL OR TRIM(PROMO_ID) = '' OR UPPER(TRIM(PROMO_ID)) = 'NULL') AS ROWS_WITHOUT_VALID_PROMO_ID,
    COUNT_IF(PROMO_ID IS NOT NULL AND TRIM(PROMO_ID) <> '' AND UPPER(TRIM(PROMO_ID)) <> 'NULL') AS ROWS_WITH_PROMO_ID
FROM SALES_TRANSACTIONS;
